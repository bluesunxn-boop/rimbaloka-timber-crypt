export const CHARACTER_MAP: Record<CharacterId, CharacterDef> = CHARACTERS.reduce(
  (acc, ch) => {
    acc[ch.id] = ch;
    return acc;
  },
  {} as Record<CharacterId, CharacterDef>
);

export function isCharacterSynergyActive(
  charId: CharacterId,
  classId: HeroClassId
): boolean {
  const ch = CHARACTER_MAP[charId];
  if (!ch) return false;
  return ch.synergyClass === 'any' || ch.synergyClass === classId;
}
