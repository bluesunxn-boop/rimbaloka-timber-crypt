export function getWeaponRarityStyle(weapon: WeaponDef) {
  const base = RARITY_META[weapon.rarity];
  if (weapon.id === 'sandal_swallow') {
    return {
      ...base,
      color: weapon.color,
      border: 'border-purple-400/80',
      bg: 'bg-purple-950/65',
      glow: 'shadow-[0_0_16px_rgba(192,132,252,0.28)]',
    };
  }
  return base;
}

export function getRecipeRarityStyle(recipe: CraftingRecipe) {
  if (recipe.weaponId && WEAPONS[recipe.weaponId]) {
    return getWeaponRarityStyle(WEAPONS[recipe.weaponId]);
  }
  return RARITY_META[recipe.rarity];
}

